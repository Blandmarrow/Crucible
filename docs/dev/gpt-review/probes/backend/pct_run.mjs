import { createRequire } from "module";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import os from "os";
const here = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(here, "../../../../..");
const require = createRequire(path.join(REPO, "frontend") + "/");
const ts = require("typescript");
let src = fs.readFileSync(path.join(REPO, "frontend/src/utils/percentile.ts"), "utf8");
// scratch copy only: drop the two imports (type import + a label helper unused by percentileOf)
src = src.replace(/^import type .*$/m, "").replace(/^import \{ styleModeLabel \}.*$/m, "const styleModeLabel = (x) => String(x);");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 } }).outputText;
const f = path.join(os.tmpdir(), "gpt-review-percentile.scratch.mjs");
fs.writeFileSync(f, js);
const { percentileOf } = await import(f);
const q = JSON.parse(process.argv[2]);
const out = {};
for (const s of [0, 0.25, 0.5, 0.75, 1]) out[String(s)] = percentileOf(s, q);
console.log(JSON.stringify(out));
