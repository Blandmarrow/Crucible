import { test, expect } from '@playwright/test'
import { createDatasetViaApi, uploadViaApi } from './helpers'
test('extra: 031 selection cleared after invalid regex; 029 Edit Captions cancel focus', async ({ page, request }) => {
  const ds = await createDatasetViaApi(request, `fx-${Date.now()}`)
  await uploadViaApi(request, ds.id, 'x.png')
  await page.goto(`/datasets/${ds.id}/gallery`)
  await page.getByTestId('select-all-btn').click()
  await expect(page.getByText('1 selected')).toBeVisible()
  const open = page.getByRole('button', { name: 'Edit', exact: true })
  await open.click()
  const m = page.locator('div.fixed.inset-0').filter({ hasText: 'Edit Captions' })
  await m.getByRole('button', { name: 'Cancel' }).click()
  await expect(m).toHaveCount(0)
  console.log('EXTRA 029 EditCaptions focus after cancel:', await page.evaluate(() => document.activeElement?.tagName), ' opener focused:', await open.evaluate((e: Element) => e === document.activeElement))
  await open.click()
  await m.getByRole('button', { name: 'Find & Replace' }).click()
  await m.getByPlaceholder('Text to find…').fill('(')
  await m.getByLabel('Use regular expression').check()
  await m.getByRole('button', { name: 'Apply' }).click()
  await expect(page.getByText('No captions matched')).toBeVisible()
  await expect(m).toHaveCount(0)
  console.log('EXTRA 031 "1 selected" count after invalid regex:', await page.getByText('1 selected').count())
})
